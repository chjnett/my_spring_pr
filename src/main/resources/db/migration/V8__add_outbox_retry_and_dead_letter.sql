alter table audit_outbox
    drop constraint ck_audit_outbox_status;

alter table audit_outbox
    add constraint ck_audit_outbox_status
        check (status in ('PENDING', 'PUBLISHED', 'FAILED'));

alter table audit_outbox
    add column attempt_count integer not null default 0;

alter table audit_outbox
    add column next_attempt_at timestamp with time zone;

alter table audit_outbox
    add column last_error varchar(1000);

alter table audit_outbox
    add column failed_at timestamp with time zone;

update audit_outbox
set next_attempt_at = created_at
where status = 'PENDING';

create index idx_audit_outbox_due
    on audit_outbox (status, next_attempt_at, id);

create table audit_outbox_dead_letter (
    id bigint generated by default as identity primary key,
    outbox_id bigint not null,
    event_id varchar(36) not null,
    aggregate_type varchar(50) not null,
    aggregate_id varchar(100) not null,
    event_type varchar(80) not null,
    actor_id bigint not null,
    payload text not null,
    attempt_count integer not null,
    last_error varchar(1000) not null,
    failed_at timestamp with time zone not null,
    created_at timestamp with time zone not null,
    constraint uk_audit_outbox_dead_letter_event_id unique (event_id)
);

create index idx_audit_outbox_dead_letter_failed_at
    on audit_outbox_dead_letter (failed_at desc);
