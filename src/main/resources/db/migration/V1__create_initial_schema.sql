create table users (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    email varchar(255) not null,
    constraint uk_user_email unique (email)
);

create table role_grants (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    role varchar(30) not null,
    constraint uk_role_grant_user_role unique (user_id, role)
);

create table idempotency_records (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    request_scope varchar(100) not null,
    idempotency_key varchar(255) not null,
    request_hash varchar(64) not null,
    status varchar(20) not null,
    response_grant_id bigint,
    response_role varchar(30),
    created_at timestamp with time zone not null,
    constraint uk_idempotency_user_scope_key
        unique (user_id, request_scope, idempotency_key)
);
