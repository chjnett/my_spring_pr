create table audit_outbox (
    id bigint generated by default as identity primary key,
    event_id varchar(36) not null,
    aggregate_type varchar(50) not null,
    aggregate_id varchar(100) not null,
    event_type varchar(80) not null,
    actor_id bigint not null,
    payload text not null,
    status varchar(20) not null,
    created_at timestamp with time zone not null,
    published_at timestamp with time zone,
    constraint uk_audit_outbox_event_id unique (event_id),
    constraint ck_audit_outbox_status check (status in ('PENDING', 'PUBLISHED'))
);

create index idx_audit_outbox_status_id on audit_outbox (status, id);

create table security_events (
    id bigint generated by default as identity primary key,
    event_id varchar(36) not null,
    aggregate_type varchar(50) not null,
    aggregate_id varchar(100) not null,
    event_type varchar(80) not null,
    actor_id bigint not null,
    payload text not null,
    occurred_at timestamp with time zone not null,
    ingested_at timestamp with time zone not null,
    constraint uk_security_events_event_id unique (event_id)
);

create index idx_security_events_type_occurred_at
    on security_events (event_type, occurred_at desc);
create index idx_security_events_actor_occurred_at
    on security_events (actor_id, occurred_at desc);
