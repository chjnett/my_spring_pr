create table security_alerts (
    id bigint generated by default as identity primary key,
    fingerprint varchar(64) not null,
    rule_code varchar(50) not null,
    severity varchar(20) not null,
    status varchar(20) not null,
    subject_type varchar(20) not null,
    subject_value varchar(100) not null,
    event_count bigint not null,
    window_start timestamp with time zone not null,
    window_end timestamp with time zone not null,
    first_event_at timestamp with time zone not null,
    last_event_at timestamp with time zone not null,
    assignee_id bigint,
    resolution_note varchar(1000),
    updated_by bigint,
    version bigint not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_security_alerts_fingerprint unique (fingerprint),
    constraint ck_security_alerts_status check (status in ('OPEN', 'INVESTIGATING', 'RESOLVED')),
    constraint ck_security_alerts_severity check (severity in ('MEDIUM', 'HIGH', 'CRITICAL'))
);

create index idx_security_alerts_status_created
    on security_alerts (status, created_at desc);

create table detection_watermarks (
    pipeline varchar(50) primary key,
    watermark timestamp with time zone not null,
    updated_at timestamp with time zone not null
);
